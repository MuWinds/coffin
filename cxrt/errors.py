"""``rt`` 自己的异常类型：设备运行时错误与内核构建错误分开。

Module: ``coffin/cxrt``。叶子模块，只 import 标准库。**不 import
torch**：这一层存在的全部理由，就是 corex 推理链上不再有 torch。

Constraints:
    * 两类错误不能合并。构建失败（工具链、源码、链接）与运行时失败（驱动返回码、
      非法参数）排查路径完全不同，调用方按类型决定「回退到别的后端」还是「把这次
      请求判为失败」。
    * 消息里必须带数字与名字。``cudaErrorInvalidValue`` 这类字符串自身不指出是哪次
      分配、哪个入口，排障时唯一有用的是「哪个符号、哪个尺寸、哪个返回码」。
"""

from __future__ import annotations


class RtError(RuntimeError):
    """设备运行时的一次失败：驱动返回码、非法参数或越界访问。

    与 :class:`BuildError` 的区别在恢复方式：这里失败说明「这台机器现在不能算」，
    调用方应当让本次推理失败或换后端；构建失败说明「这台机器编不出来」，通常意味着
    工具链缺失，可以退回参考实现。
    """


class BuildError(RuntimeError):
    """内核 shim 的编译或链接失败。

    ``str(exc)`` 里至少有编译器命令行与输出末尾几百字节：没有命令行的构建错误
    在集群上无法复现，因为没有命令行的构建错误无法复现（同一棵树、不同环境变量
    会编出不同的目标文件）。
    """


class ShapeError(ValueError):
    """算子参数与内核索引方式矛盾：dtype、连续性、行间距或形状不匹配。

    继承 ``ValueError`` 而不是 ``RtError``：这是调用方的调用错误，不是设备的失败，
    把它和设备错误混在一起会让人去查卡。
    """
